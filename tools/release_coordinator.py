"""A release coordinator in SHADOW mode: read the pinned inputs, report every gate, change nothing.

HR-05 (health review 23.11.2026) asks for one fail-closed coordinator instead of per-release
kits generated by hand. Its first step is a shadow: run beside the kit for a few releases,
compare, and only then let it gate anything. This is that shadow, offline.

**What it reads** (files only; paths given on the command line):

* the kit's ``release.env`` (``TARGET``, ``PREVIOUS``, ``ARCHIVE_SHA``, ``SCANNED_IMAGE_ID``,
  ``RELEASE_NOTE_KIND``);
* the release image's manifest (``release-manifest-<tag>.txt``) and the archive's
  ``.sha256`` file, optionally the archive itself (hashed, never extracted);
* the expected-migrations file (``tools/release_migrations.py derive``), optionally the
  reviewed local plan with ``--repo`` (to re-derive it from git), and optionally a
  ``migration_plan`` output captured by d1 (``plan.txt``).

**What it does:** checks that every pinned value agrees with every other, writes a report
(one line per gate: ``PASS``, ``FAIL`` or ``MISSING``, plus the sha256 of each input), and
exits 0 only when every gate passes, 3 otherwise. ``MISSING`` is not a pass: a gate whose
evidence is absent is reported, never assumed.

**What it never does:** it never runs docker, ssh, a database or ``manage.py``; never
writes outside ``--report``; never deploys, migrates, swaps, rolls back or bypasses a gate.
Its verdict is advice beside the kit's own gates, which stay authoritative. Activating it
in the production workflow is an owner decision (HR-05 note, «shadow»).
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from types import ModuleType

EXIT_NOT_READY = 3
_SHA = re.compile(r"[0-9a-f]{40}")
_SHA256 = re.compile(r"[0-9a-f]{64}")
_IMAGE_ID = re.compile(r"sha256:[0-9a-f]{64}")
_ENV_KEYS = ("TARGET", "PREVIOUS", "ARCHIVE_SHA", "SCANNED_IMAGE_ID", "RELEASE_NOTE_KIND")
#: Every gate the report must carry, in report order. A gate that did not run (its input
#: missing, empty or unreadable) is reported MISSING: never left out, never a pass.
ALL_GATES = (
    "release.env:keys",
    "release.env:commits",
    "manifest:revision",
    "manifest:previous",
    "manifest:image_tag",
    "manifest:image_ids",
    "manifest:runtime_check",
    "manifest:image_scan",
    "manifest:release_note",
    "manifest:loaded_check",
    "archive:sha256",
    "archive:bytes",
    "migrations:file",
    "migrations:commits",
    "migrations:derived",
    "migrations:live_plan",
)


def _sibling(name: str) -> ModuleType:
    """Load ``tools/<name>.py`` by path: under ``python -I`` the script's directory is not
    on ``sys.path``, and nothing else may be imported in its place."""
    path = Path(__file__).with_name(f"{name}.py")
    spec = importlib.util.spec_from_file_location(f"_coordinator_{name}", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module  # dataclasses resolve annotations through sys.modules
    # Never write tools/__pycache__ (``-I`` does not imply ``-B``): the shadow writes only
    # its report.
    previous, sys.dont_write_bytecode = sys.dont_write_bytecode, True
    try:
        spec.loader.exec_module(module)
    finally:
        sys.dont_write_bytecode = previous
    return module


@dataclass(frozen=True)
class Gate:
    name: str
    status: str  # PASS | FAIL | MISSING
    detail: str


def read_env(text: str) -> dict[str, str]:
    """``KEY=value`` lines of a kit's release.env; comments and blanks skipped; any other
    line, or a key twice, is an error (the file is data, never sourced here)."""
    values: dict[str, str] = {}
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, sep, value = line.partition("=")
        if not sep or not re.fullmatch(r"[A-Z_][A-Z0-9_]*", key) or key in values:
            raise ValueError(f"release.env: unreadable line {line[:40]!r}")
        values[key] = value
    return values


def read_manifest(text: str) -> dict[str, str]:
    """``key: value`` lines of a release manifest; a key twice is an error."""
    values: dict[str, str] = {}
    for line in text.splitlines():
        if not line.strip():
            continue
        key, sep, value = line.partition(":")
        if not sep or not re.fullmatch(r"[a-z_0-9]+", key) or key in values:
            raise ValueError(f"manifest: unreadable line {line[:40]!r}")
        values[key] = value.strip()
    return values


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def shadow(
    *,
    release_env: Path,
    manifest: Path,
    archive_sha_file: Path,
    expected_migrations: Path,
    archive: Path | None = None,
    plan: Path | None = None,
    repo: Path | None = None,
    reviewed_plan: Path | None = None,
) -> tuple[list[Gate], dict[str, str]]:
    """Every gate's result, and the sha256 of each input read."""
    rm = _sibling("release_migrations")
    gates: list[Gate] = []
    inputs: dict[str, str] = {}

    def gate(name: str, ok: bool | None, detail: str) -> None:
        status = "MISSING" if ok is None else ("PASS" if ok else "FAIL")
        gates.append(Gate(name, status, detail))

    def read(label: str, path: Path) -> str | None:
        try:
            data = path.read_bytes()
        except OSError as error:
            gate(f"input:{label}", None, f"{path}: {error.strerror}")
            return None
        inputs[label] = hashlib.sha256(data).hexdigest()
        try:
            return data.decode("utf-8")
        except UnicodeDecodeError:
            gate(f"input:{label}", False, f"{path}: not UTF-8")
            return None

    env_text = read("release.env", release_env)
    mf_text = read("manifest", manifest)
    sha_text = read("archive.sha256", archive_sha_file)
    exp_text = read("expected-migrations", expected_migrations)

    env: dict[str, str] = {}
    if env_text is not None:
        try:
            env = read_env(env_text)
        except ValueError as error:
            gate("release.env", False, str(error))
    missing = [k for k in _ENV_KEYS if k not in env]
    gate(
        "release.env:keys",
        not missing if env_text is not None else None,
        f"missing {missing}" if missing else "all present",
    )
    target, previous = env.get("TARGET", ""), env.get("PREVIOUS", "")
    gate(
        "release.env:commits",
        bool(_SHA.fullmatch(target) and _SHA.fullmatch(previous) and target != previous),
        f"TARGET {target[:12]} PREVIOUS {previous[:12]}",
    )

    mf: dict[str, str] = {}
    if mf_text is not None:
        try:
            mf = read_manifest(mf_text)
        except ValueError as error:
            gate("manifest", False, str(error))
        else:
            if not mf:
                gate("manifest", False, f"{manifest}: no key: value line (empty manifest)")
    if mf:
        gate(
            "manifest:revision",
            mf.get("revision") == target,
            f"revision {mf.get('revision', '')[:12]}",
        )
        gate(
            "manifest:previous",
            mf.get("previous") == previous,
            f"previous {mf.get('previous', '')[:12]}",
        )
        tag = f"juristid-main-web:{target[:12]}"
        gate(
            "manifest:image_tag", mf.get("image_tag") == tag, f"{mf.get('image_tag')} (want {tag})"
        )
        ids = {
            k: mf.get(k, "")
            for k in (
                "image_id",
                "scanned_image_id",
                "runtime_checked_image_id",
                "archive_image_id",
            )
        }
        same = len(set(ids.values())) == 1 and bool(_IMAGE_ID.fullmatch(ids["image_id"]))
        gate(
            "manifest:image_ids",
            same and ids["image_id"] == env.get("SCANNED_IMAGE_ID"),
            "built = scanned = runtime-checked = archived = release.env SCANNED_IMAGE_ID",
        )
        gate(
            "manifest:runtime_check",
            mf.get("runtime_check", "").startswith("PASS "),
            mf.get("runtime_check", "")[:40],
        )
        gate(
            "manifest:image_scan",
            mf.get("image_scan", "").startswith("PASS ")
            and mf.get("image_scan_fixable_high_critical") == "0",
            mf.get("image_scan", "")[:40],
        )
        gate(
            "manifest:release_note",
            mf.get("release_note", "").split(" ", 1)[0] == env.get("RELEASE_NOTE_KIND"),
            f"{mf.get('release_note', '')[:30]} vs {env.get('RELEASE_NOTE_KIND')}",
        )
        loaded = mf.get("loaded_check")
        gate(
            "manifest:loaded_check",
            None if loaded is None else loaded == f"PASS {ids['image_id']}",
            "no loaded_check line (HR-05 s.4: --check-loaded not yet run in CI)"
            if loaded is None
            else loaded[:40],
        )

    if sha_text is not None and mf:
        parts = sha_text.split()
        ok = (
            len(parts) == 2
            and _SHA256.fullmatch(parts[0]) is not None
            and parts[0] == mf.get("archive_sha256") == env.get("ARCHIVE_SHA")
            and parts[1] == mf.get("archive")
        )
        gate(
            "archive:sha256",
            ok,
            ".sha256 file = manifest archive_sha256 = release.env ARCHIVE_SHA, same file name",
        )
    if archive is None:
        gate(
            "archive:bytes",
            None,
            "archive not given (hashed on the host by verify-release-artifact.sh)",
        )
    elif archive.is_file():
        got = _sha256_file(archive)
        inputs["archive"] = got
        gate("archive:bytes", got == env.get("ARCHIVE_SHA"), f"sha256 {got[:16]}...")
    else:
        gate("archive:bytes", False, f"{archive} is not a file")

    expected = None
    if exp_text is not None:
        try:
            expected = rm.parse_expected(exp_text)
        except rm.Refused as error:
            gate("migrations:file", False, str(error))
    if expected is not None:
        gate(
            "migrations:file",
            True,
            f"{len(expected.migrations)} [{' '.join(expected.plan.labels)}]",
        )
        gate(
            "migrations:commits",
            expected.previous == previous and expected.target == target,
            "expected-migrations previous/target = release.env",
        )
        if repo is not None and reviewed_plan is not None:
            try:
                again = rm.derive_expected(
                    repo=repo,
                    previous=previous,
                    target=target,
                    reviewed_plan=reviewed_plan.read_text(encoding="utf-8"),
                    helper=None,
                )
                gate(
                    "migrations:derived",
                    again.render() == exp_text,
                    "re-derived from git + the reviewed plan",
                )
            except (rm.Refused, OSError) as error:
                gate("migrations:derived", False, str(error))
        else:
            gate(
                "migrations:derived", None, "not re-derived (--repo and --reviewed-plan not given)"
            )
        if plan is None:
            gate("migrations:live_plan", None, "no captured migration_plan (d1 plan.txt) given")
        else:
            try:
                live = plan.read_bytes().decode("utf-8")
                inputs["plan.txt"] = hashlib.sha256(live.encode("utf-8")).hexdigest()
                got = rm.check_plan(expected, live)
                gate(
                    "migrations:live_plan",
                    True,
                    f"MATCH {len(got.pending)} [{' '.join(got.labels)}]",
                )
            except (rm.Refused, OSError, UnicodeDecodeError) as error:
                gate("migrations:live_plan", False, str(error))
    reported = {g.name for g in gates}
    for name in ALL_GATES:
        if name not in reported:
            gate(name, None, "did not run: its input is missing, empty or unreadable")
    order = {name: index for index, name in enumerate(ALL_GATES)}
    gates.sort(key=lambda g: order.get(g.name, -1))  # input/parse failures first
    return gates, inputs


def render(gates: list[Gate], inputs: dict[str, str]) -> str:
    bad = [g for g in gates if g.status != "PASS"]
    rows = ["juristid release coordinator - SHADOW report (advice only; the kit's gates decide)"]
    rows += [f"input {name} sha256 {digest}" for name, digest in sorted(inputs.items())]
    rows += [f"{g.status:<7} {g.name}: {g.detail}" for g in gates]
    rows.append(
        "VERDICT: every gate passes"
        if not bad
        else f"VERDICT: NOT READY - {len(bad)} gate(s) not passed: {', '.join(g.name for g in bad)}"
    )
    return "\n".join(rows) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Release coordinator, shadow mode (read-only).")
    parser.add_argument("--release-env", type=Path, required=True)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--archive-sha-file", type=Path, required=True)
    parser.add_argument("--expected-migrations", type=Path, required=True)
    parser.add_argument("--archive", type=Path)
    parser.add_argument("--plan", type=Path, help="a migration_plan output captured by d1")
    parser.add_argument("--repo", type=Path)
    parser.add_argument("--reviewed-plan", type=Path)
    parser.add_argument("--report", type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        report = args.report.open("x", encoding="utf-8", newline="\n")
    except FileExistsError:
        sys.stderr.write(
            f"release_coordinator: {args.report} exists; reports are never overwritten\n"
        )
        return 2
    gates, inputs = shadow(
        release_env=args.release_env,
        manifest=args.manifest,
        archive_sha_file=args.archive_sha_file,
        expected_migrations=args.expected_migrations,
        archive=args.archive,
        plan=args.plan,
        repo=args.repo,
        reviewed_plan=args.reviewed_plan,
    )
    text = render(gates, inputs)
    with report:
        report.write(text)
    sys.stdout.write(text.encode("ascii", "backslashreplace").decode("ascii"))
    return 0 if all(g.status == "PASS" for g in gates) else EXIT_NOT_READY


if __name__ == "__main__":
    raise SystemExit(main())
