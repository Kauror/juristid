def read_staged_files() -> str:
    """Drain the staged queue the way the deployment does.

    A subprocess rather than an in-process call, because that is what actually
    runs on the server: a separate process with its own database connection,
    seeing rows a web request committed. The settings module is forced for the
    same reason `e2e/test_document_content.py::run_worker` forces it — pytest
    sets the test settings for its own process and those mint a fresh temporary
    storage root, so a child inheriting them would look in an empty directory.
    """
    environment = {**os.environ, "DJANGO_SETTINGS_MODULE": "config.settings"}
    result = subprocess.run(
        [sys.executable, "manage.py", "extract_pending_intake_files", "--limit", "20"],
        cwd=REPOSITORY_ROOT,
        env=environment,
        capture_output=True,
        text=True,
        timeout=300,
        check=False,
    )
    report = "\n".join(["stdout:", result.stdout, "stderr:", result.stderr])
    assert result.returncode == 0, report
    # A worker that ran and found nothing is the failure this helper exists to
    # catch, and it is invisible unless asserted.
    assert "Loetud 0 faili" not in result.stdout, report
    return report


def open_create(page, base_url: str) -> None:
    page.goto(f"{base_url}/teemad/uus/")
    expect(page.get_by_role("heading", name="Uus teema")).to_be_visible()


def choose(page, paths: list[Path]) -> None:
    page.locator("#id_files").set_input_files([str(path) for path in paths])


def staged_rows(page):
    return page.locator("#intake-failid .dropzone__file")


def wait_for_reading(page) -> None:
    """The upload has landed and the page says what is happening."""
    expect(page.locator("#intake-panel")).to_have_attribute("data-intake-state", "reading")


def wait_for_suggestions(page) -> None:
    expect(page.locator("#intake-panel")).to_have_attribute(
        "data-intake-state", "ready", timeout=30_000
    )
    expect(page.get_by_role("heading", name="Failist leitud")).to_be_visible()


def open_documents(page) -> None:
    page.get_by_role("link", name=re.compile(r"^Dokumendid")).click()
    page.wait_for_load_state("networkidle")


def name_a_next_step(page) -> None:
    """Say what happens next, as a lawyer filing a real Teema would.

    Not decoration: a Teema this suite leaves behind with no next action joins
    the department's «järgmise tegevuseta» population permanently, and
    `e2e/test_kpi_navigation.py` reads the first rows of that list
    (e2e/test_uus_teema_files.py).
    """
    page.fill("#id_next-text", "Lugeda eelnõu ja koostada arvamus")
    page.locator("#jargmine-tegevus").get_by_role("button", name="+1 nädal").click()


def register_holds(page, base_url: str, title: str) -> int:
    """How many register rows carry this title. Zero is the assertion we want.

    Asked through the ordinary register rather than the database, because this
    suite deliberately has no database access: a browser test that read around
    the UI could mask exactly the authorization and visibility defects it is
    here to catch (e2e/conftest.py).

    In a tab of its own, so asking the question does not navigate away from the
    half-filled form that is the subject of it.
    """
    other = page.context.new_page()
    try:
        other.goto(f"{base_url}/teemad/")
        return other.get_by_role("link", name=title, exact=True).count()
    finally:
        other.close()


def test_the_letter_is_read_on_the_create_form_and_the_teema_keeps_what_was_confirmed(
    page, base_url, screenshots, letter_pdf
) -> None:
    """The whole workflow, in the order somebody performs it.

    One journey, without leaving the form: choose, watch it be read, take what
    it found, write a title, press the button once. The register is asked twice
    from a tab of its own, so «nothing exists yet» is checked without
    abandoning the half-filled page it is a claim about.
    """
    sign_in(page, base_url, SANDRA)
    title = "Pakendiseaduse muudatus, loetud loomisel"
    assert register_holds(page, base_url, title) == 0

    # -- 1. choose the file; it uploads itself and says so ------------------
    open_create(page, base_url)
    choose(page, [letter_pdf])
    wait_for_reading(page)
    expect(staged_rows(page)).to_have_count(1)
    expect(page.locator("#intake-failid")).to_contain_text("kaaskiri.pdf")
    expect(page.locator("#intake-panel")).to_contain_text("Loen faili")
    # Words a person can act on, and none of the stored vocabulary.
    panel = page.locator("#intake-panel").inner_text()
    assert "PENDING" not in panel and "Teksti eraldamine" not in panel
    screenshots(page, "40-uus-teema-loen-faili")

    # -- 2. the worker reads it, in its own process ------------------------
    read_staged_files()
    wait_for_suggestions(page)

    # -- 3. what the letter says, with the sentence it came from -----------
    expect(
        page.get_by_text("Palume esitada arvamus hiljemalt 18. septembriks 2026").first
    ).to_be_visible()
    expect(page.get_by_text("Arvamuse tähtaeg").first).to_be_visible()
    expect(page.get_by_text("Kellelt").first).to_be_visible()
    expect(page.get_by_text("EIS").first).to_be_visible()
    # The deadline is strong and unopposed, so it is already in the box; the
    # sender is ticked in the real control. Neither is saved.
    expect(page.locator("#id_response_deadline")).to_have_value("18.9.2026")
    ministry = page.locator("label.chip", has_text="Näidisministeerium").locator("input").first
    expect(ministry).to_be_checked()
    # The title is offered and never written, on any surface.
    expect(page.locator("#id_title")).to_have_value("")
    expect(page.locator('button[data-suggest-for="title"]').first).to_be_visible()
    screenshots(page, "41-uus-teema-failist-leitud")

    # Still nothing in the register: a suggestion is a proposal, and reading a
    # file creates no business data whatsoever.
    assert register_holds(page, base_url, title) == 0

    # -- 4. take the heading, write a title over it, and file it -----------
    page.locator('button[data-suggest-for="title"]').first.click()
    expect(page.locator("#id_title")).to_have_value("Pakendiseaduse muutmise seaduse eelnõu")
    page.locator("#id_title").fill(title)
    name_a_next_step(page)
    page.get_by_role("button", name="Loo teema").click()
    page.wait_for_load_state("domcontentloaded")

    complaints = page.locator(".field__error, .formerror, .message--error").all_inner_texts()
    assert not complaints, f"the form refused: {complaints}"
    page.wait_for_url(re.compile(r"/teemad/[0-9a-f-]{36}/$"))
    matter_url = page.url

    # -- 5. exactly one Teema, carrying what was confirmed -----------------
    expect(page.get_by_role("heading", name=title)).to_be_visible()
    expect(page.get_by_text("18.9.2026").first).to_be_visible()
    assert register_holds(page, base_url, title) == 1

    # -- 6. and the file is under Dokumendid, openable, byte for byte ------
    page.goto(matter_url)
    open_documents(page)
    expect(page.get_by_role("link", name="kaaskiri.pdf", exact=True)).to_be_visible()

    with page.expect_download() as download:
        page.get_by_role("link", name="Laadi alla kaaskiri.pdf").click()
    saved = download.value
    assert saved.suggested_filename == "kaaskiri.pdf"
    assert Path(saved.path()).read_bytes() == letter_pdf.read_bytes()


def test_a_suggestion_never_overwrites_what_the_person_typed_first(
    page, base_url, letter_pdf
) -> None:
    """The rule that makes an asynchronous answer safe.

    Extraction finishes seconds after somebody has begun typing, so the test
    is: type into the two controls the letter has strong answers for *before*
    the answer arrives, and assert both survive it (task §10, §28).
    """
    sign_in(page, base_url, SANDRA)
    open_create(page, base_url)
    choose(page, [letter_pdf])
    wait_for_reading(page)

    # Typed while the file is still being read.
    page.locator("#id_title").fill(TYPED_TITLE)
    page.locator("#id_response_deadline").fill("30.9.2026")
    page.locator("label.chip", has_text="Näidisamet").locator("input").first.check()

    read_staged_files()
    wait_for_suggestions(page)

    # The letter says 18.9.2026 and names the ministry. Neither is written over.
    expect(page.locator("#id_title")).to_have_value(TYPED_TITLE)
    expect(page.locator("#id_response_deadline")).to_have_value("30.9.2026")
    expect(
        page.locator("label.chip", has_text="Näidisministeerium").locator("input").first
    ).not_to_be_checked()
    expect(page.locator("label.chip", has_text="Näidisamet").locator("input").first).to_be_checked()

    # And both candidates are still offered beside what was typed, so nothing
    # is hidden — the person can still choose them.
    expect(page.locator('button[data-suggest-for="response_deadline"]').first).to_be_visible()


def test_a_file_taken_back_off_stops_suggesting_and_is_not_filed(
    page, base_url, letter_pdf, annex_pdf
) -> None:
    """The browser and the server must not disagree about a file half gone."""
    sign_in(page, base_url, SANDRA)
    title = "Ainult lisa jäi alles"
    open_create(page, base_url)
    choose(page, [letter_pdf, annex_pdf])
    expect(staged_rows(page)).to_have_count(2)
    read_staged_files()
    wait_for_suggestions(page)
    expect(page.locator("#id_response_deadline")).to_have_value("18.9.2026")

    page.locator("[data-intake-remove]").first.click()
    expect(staged_rows(page)).to_have_count(1)
    expect(page.locator("#intake-failid")).to_contain_text("lisa.pdf")
    expect(page.locator("#intake-failid")).not_to_contain_text("kaaskiri.pdf")
    # The removed letter's deadline is no longer offered by anything.
    expect(page.locator('button[data-suggest-for="response_deadline"]')).to_have_count(0)

    page.locator("#id_title").fill(title)
    name_a_next_step(page)
    page.get_by_role("button", name="Loo teema").click()
    page.wait_for_url(re.compile(r"/teemad/[0-9a-f-]{36}/$"))

    open_documents(page)
    expect(page.get_by_role("link", name="lisa.pdf", exact=True)).to_be_visible()
    expect(page.get_by_role("link", name="kaaskiri.pdf", exact=True)).to_have_count(0)


