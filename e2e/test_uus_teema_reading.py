def test_uploading_a_document_later_starts_no_reading_workflow(
    page, base_url, letter_pdf, annex_pdf
) -> None:
    """Assisted reading belongs to the initial files, and stops there.

    A file added to a Teema that already exists is processed and indexed like
    any other; it does not reopen the suggestion workflow and it changes no
    field of the Matter (task §14, §35).
    """
    sign_in(page, base_url, SANDRA)
    title = "Hilisem fail ei muuda midagi"
    open_create(page, base_url)
    choose(page, [annex_pdf])
    read_staged_files()
    page.locator("#id_title").fill(title)
    page.locator("#id_response_deadline").fill("1.10.2026")
    name_a_next_step(page)
    page.get_by_role("button", name="Loo teema").click()
    page.wait_for_url(re.compile(r"/teemad/[0-9a-f-]{36}/$"))
    matter_url = page.url

    open_documents(page)
    page.get_by_role("button", name="↑ Lae dokument").click()
    page.locator("#lae-dokument input[name='upload']").set_input_files(str(letter_pdf))
    page.get_by_role("button", name="Salvesta dokument").click()
    page.wait_for_load_state("networkidle")
    expect(page.get_by_role("link", name="kaaskiri.pdf", exact=True)).to_be_visible()
    read_staged_files_is_a_noop()

    # The letter states 18.9.2026 and names a ministry. Neither reaches the
    # Matter, and no suggestion panel appears anywhere.
    page.goto(matter_url)
    expect(page.get_by_text("1.10.2026").first).to_be_visible()
    expect(page.get_by_text("18.9.2026")).to_have_count(0)
    expect(page.locator("#intake-panel")).to_have_count(0)
    expect(page.get_by_role("heading", name="Failist leitud")).to_have_count(0)


def read_staged_files_is_a_noop() -> None:
    """The staged queue is empty, because a later upload stages nothing.

    Deliberately asserted rather than skipped: "no staging was started" is the
    product decision this test is named after, and the only way to see it from
    a process with no database is that the queue the worker drains is empty.
    """
    environment = {**os.environ, "DJANGO_SETTINGS_MODULE": "config.settings"}
    result = subprocess.run(
        [sys.executable, "manage.py", "extract_pending_intake_files", "--limit", "20"],
        cwd=REPOSITORY_ROOT,
        env=environment,
        capture_output=True,
        text=True,
        timeout=300,
        check=False,
    )
    assert result.returncode == 0, result.stderr
    assert "Ootel: 0 ettevalmistatud faili" in result.stdout, result.stdout
